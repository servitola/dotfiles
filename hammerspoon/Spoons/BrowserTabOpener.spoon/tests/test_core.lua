local core = require "core"

eq(pcall(core.check, "github.com", "https://github.com", nil), true, "check: pattern and url")
eq(pcall(core.check, "github.com", "https://github.com", { prefer = "true" }), true, "check: with prefer")
eq(pcall(core.check, "github.com", nil, nil), false, "check: url is required")
eq(pcall(core.check, nil, "https://github.com", nil), false, "check: pattern is required")
eq(pcall(core.check, "", "https://github.com", nil), false, "check: an empty pattern matches every tab")
eq(pcall(core.check, "github.com", "", nil), false, "check: empty url")
eq(pcall(core.check, "github.com", "https://github.com", "prefer"), false, "check: options is a table")
eq(pcall(core.check, "github.com", "https://github.com", { prefer = 1 }), false, "check: prefer is JavaScript text")
eq(pcall(core.check, "github.com", "https://github.com", { perfer = "true" }), false, "check: a misspelt option is an error")

eq(core.condition(nil), "", "condition: none")
eq(core.condition("!document.hidden"), "String(!!(!document.hidden))", "condition: always answers true or false")

local script = core.script("com.vivaldi.Vivaldi")
eq(script:find('tell application id "com.vivaldi.Vivaldi"', 1, true) ~= nil, true, "script: addresses the browser by bundle id")
eq(script:find("item 1 of argv", 1, true) ~= nil, true, "script: the pattern arrives as an argument, never as text in the script")
eq(script:find("item 2 of argv", 1, true) ~= nil, true, "script: so does the condition")
eq(pcall(core.script, 'x" & (do shell script "id") & "'), false, "script: a bundle id that could leave its quotes is refused")
eq(pcall(core.script, "com.example app"), false, "script: no spaces in a bundle id")
eq(pcall(core.script, nil), false, "script: a bundle id is required")
eq(pcall(core.script, "org.mozilla.firefox"), true, "script: any well-formed bundle id")

local status, note = core.result(0, "ok\n")
eq(status, "ok", "result: switched to a tab")
eq(note, nil, "result: nothing to report")
status, note = core.result(0, "none\n")
eq(status, "none", "result: no matching tab")
status, note = core.result(0, "ok\nExecuting JavaScript through AppleScript is turned off.\n")
eq(status, "ok", "result: switched although the condition could not run")
eq(note, "Executing JavaScript through AppleScript is turned off.", "result: why the condition could not run")
eq(core.result(0, nil), "failed", "result: no output")
eq(core.result(1, ""), "failed", "result: the script did not run")

eq(core.problem("execution error: Not authorized to send Apple events to Vivaldi. (-1743)"), "denied", "problem: macOS refused automation")
eq(core.problem("syntax error: Expected end of line but found identifier. (-2741)"), "unsupported", "problem: the browser has no tab scripting")
eq(core.problem(""), "unsupported", "problem: anything else")

local site = core.site("github", { pattern = "github.com", url = "https://github.com" })
eq(site.pattern, "github.com", "site: pattern")
eq(site.url, "https://github.com", "site: url")
eq(site.options, nil, "site: no options")
site = core.site("playing", { pattern = "youtube.com/watch", url = "https://youtube.com", prefer = "true" })
eq(site.options.prefer, "true", "site: prefer becomes an option")

local ok, message = pcall(core.site, "github", nil)
eq(ok, false, "site: unknown name raises")
eq(message:find('"github"', 1, true) ~= nil, true, "site: the error names it")
ok, message = pcall(core.site, "github", { "github.com", "https://github.com" })
eq(ok, false, "site: fields are named")
eq(message:find("pattern", 1, true) ~= nil, true, "site: the error says which field is missing")
eq(pcall(core.site, "github", { pattern = "github.com" }), false, "site: url is required")
eq(pcall(core.site, "github", { pattern = "github.com", url = "https://github.com", hotkey = "g" }), false, "site: an unknown field is an error")
